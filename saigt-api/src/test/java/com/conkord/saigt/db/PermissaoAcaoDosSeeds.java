package com.conkord.saigt.db;

import org.springframework.jdbc.core.JdbcTemplate;

/**
 * Os seeds de `permissao_acao` inserem a coluna `ator`, que a migração `permissao-acao-por-tipo-entidade` renomeia
 * para `tipo_entidade` (e o esquema do Hibernate já não tem). Antes dos seeds a tabela vazia ganha o esquema
 * antigo; depois, a conversão que a migração faz.
 */
final class PermissaoAcaoDosSeeds {

    private PermissaoAcaoDosSeeds() {
    }

    static void prepararEsquemaAntigo(JdbcTemplate jdbcTemplate) {
        Integer linhas = jdbcTemplate.queryForObject("SELECT count(*) FROM permissao_acao", Integer.class);
        if (linhas != null && linhas == 0 && !colunaAtorExiste(jdbcTemplate)) {
            jdbcTemplate.execute("DROP TABLE permissao_acao");
            jdbcTemplate.execute("CREATE TABLE permissao_acao (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                    + "ator VARCHAR(10) NOT NULL, instrumento_procedimento_config_id BIGINT NOT NULL, "
                    + "ativo BOOLEAN DEFAULT TRUE NOT NULL, "
                    + "CONSTRAINT uq_permissao_acao UNIQUE (instrumento_procedimento_config_id, ator))");
        }
    }

    static void converterParaTipoEntidade(JdbcTemplate jdbcTemplate) {
        if (colunaAtorExiste(jdbcTemplate)) {
            jdbcTemplate.update("UPDATE permissao_acao SET ator = 'CM' WHERE ator = 'ENTIDADE'");
            jdbcTemplate.execute("ALTER TABLE permissao_acao ALTER COLUMN ator RENAME TO tipo_entidade");
            jdbcTemplate.execute("ALTER TABLE permissao_acao ALTER COLUMN tipo_entidade VARCHAR(30)");
        }
    }

    private static boolean colunaAtorExiste(JdbcTemplate jdbcTemplate) {
        Integer colunas = jdbcTemplate.queryForObject("SELECT count(*) FROM information_schema.columns "
                + "WHERE lower(table_name) = 'permissao_acao' AND lower(column_name) = 'ator'", Integer.class);
        return colunas != null && colunas > 0;
    }
}
